SR.lang = 'en';

SR.detectLang = function () {
  try {
    const saved = localStorage.getItem('sr.lang');
    if (saved === 'en' || saved === 'es') return saved;
  } catch (e) { /* storage blocked */ }
  const nav = (navigator.language || 'en').toLowerCase();
  return nav.startsWith('es') ? 'es' : 'en';
};

SR.setLang = function (lang) {
  SR.lang = lang === 'es' ? 'es' : 'en';
  try { localStorage.setItem('sr.lang', SR.lang); } catch (e) { /* ignore */ }
  document.documentElement.lang = SR.lang;
};

SR.t = function (key, vars) {
  const table = SR.I18N[SR.lang] || SR.I18N.en;
  let str = table[key] || SR.I18N.en[key] || key;
  if (vars) {
    str = str.replace(/\{(\w+)\}/g, (m, k) => (vars[k] === undefined ? m : vars[k]));
  }
  return str;
};

// Localised field from a {en, es} data object.
SR.L = function (obj) {
  if (obj == null) return '';
  if (typeof obj === 'string') return obj;
  return obj[SR.lang] || obj.en || '';
};

SR.fmt = function (n) {
  return Number(n || 0).toLocaleString(SR.lang === 'es' ? 'es-AR' : 'en-US');
};

SR.dateFmt = function (ts) {
  try {
    return new Date(ts).toLocaleString(SR.lang === 'es' ? 'es-AR' : 'en-US', {
      day: '2-digit', month: 'short', hour: '2-digit', minute: '2-digit'
    });
  } catch (e) { return ''; }
};
